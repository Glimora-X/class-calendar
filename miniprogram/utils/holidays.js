/**
 * @param {string} date YYYY-MM-DD
 * @returns {string}
 */
function holidayLabel(date) {
  return HOLIDAYS[date] || ''
}

/**
 * @param {number} year
 * @param {number} month 1-12
 * @returns {Record<string, string>}
 */
function holidaysInMonth(year, month) {
  const prefix = `${year}-${month < 10 ? `0${month}` : month}-`
  const out = {}
  Object.keys(HOLIDAYS).forEach((d) => {
    if (d.indexOf(prefix) === 0) out[d] = HOLIDAYS[d]
  })
  return out
}

